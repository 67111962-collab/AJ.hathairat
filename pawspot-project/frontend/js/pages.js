function openInfoPage(name) {
    const page = INFO_PAGES[name];
    if (!page) return;
    $('infoTitle').textContent = page.title;
    $('infoBody').innerHTML = page.html();
    $('infoBody').scrollTop = 0;
    setHash(`#${name}`);
    if (!modalStack.includes('infoModal')) openModal('infoModal');
}

function openInfoFromHash() {
    const name = location.hash.slice(1);
    if (INFO_PAGES[name]) openInfoPage(name);
}

document.addEventListener('DOMContentLoaded', () => {
    // links like <a href="#privacy"> anywhere on the page (footer, menu, inside the pages)
    document.addEventListener('click', e => {
        const a = e.target.closest('a[href^="#"]');
        if (!a) return;
        const name = a.getAttribute('href').slice(1);
        if (INFO_PAGES[name]) {
            e.preventDefault();
            openInfoPage(name);
        } else if (a.hasAttribute('data-close-info')) {
            closeModal('infoModal');
        }
    });
    openInfoFromHash();
});
window.addEventListener('hashchange', openInfoFromHash);
